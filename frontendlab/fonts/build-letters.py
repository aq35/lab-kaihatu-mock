def glyph_for(rows):
    p = TTGlyphPen(None)
    for r, row in enumerate(rows):
        for c, ch in enumerate(row):
            if ch == '1':
                x = X0 + c * PX
                y = (6 - r) * PX          # 上の行ほど高い y（baseline=0）
                p.moveTo((x, y)); p.lineTo((x + PX, y)); p.lineTo((x + PX, y + PX)); p.lineTo((x, y + PX)); p.closePath()
    return p.glyph()

def uniname(ch):
    return {'.': 'period', ',': 'comma', '!': 'exclam', '?': 'question', '-': 'hyphen', ':': 'colon', ' ': 'space'}.get(ch, ch if ch.isalnum() else 'u%04X' % ord(ch))

order = ['.notdef']
glyphs = {'.notdef': glyph_for(["11111","10001","10001","10001","10001","10001","11111"])}
cmap = {}
for ch, rows in GLYPHS.items():
    name = uniname(ch)
    order.append(name)
    glyphs[name] = glyph_for(rows)
    cmap[ord(ch)] = name

fb = FontBuilder(UPEM, isTTF=True)
fb.setupGlyphOrder(order)
fb.setupCharacterMap(cmap)
fb.setupGlyf(glyphs)
fb.setupHorizontalMetrics({n: (720, X0) for n in order})   # 5列(600)+余白 → advance 720
fb.setupHorizontalHeader(ascent=840, descent=0)
fb.setupNameTable({"familyName": "sunao Pixel", "styleName": "Regular"})
fb.setupOS2(sTypoAscender=840, sTypoDescender=0, usWinAscent=900, usWinDescent=0)
fb.setupPost()

out = sys.argv[1] if len(sys.argv) > 1 else 'sunao-pixel'
fb.font.save(out + '.ttf')
from fontTools.ttLib import TTFont
f = TTFont(out + '.ttf'); f.flavor = 'woff2'; f.save(out + '.woff2')
with open(out + '.woff2', 'rb') as fh:
    b64 = base64.b64encode(fh.read()).decode()
with open(out + '.b64', 'w') as fh:
    fh.write(b64)
print('WOFF2', os.path.getsize(out + '.woff2'), 'B  /', len(GLYPHS), 'glyphs  (base64', len(b64), 'chars)')
